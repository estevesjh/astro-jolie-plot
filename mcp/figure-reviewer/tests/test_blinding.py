"""Unit tests for physical blinding guarantees (metadata stripping, filename hiding, PDF rendering)."""

from __future__ import annotations

import io
from pathlib import Path

import pymupdf
from PIL import Image, PngImagePlugin

from mcp_figure_reviewer.blinding import (
    BLIND_FILENAME,
    IsolatedBlindSandbox,
    inspect_figure_pixels,
    prepare_blind_image,
)


def _make_leaky_png(path: Path) -> None:
    """Create a PNG loaded with leaky text metadata chunks."""
    img = Image.new("RGBA", (800, 600), (240, 245, 255, 255))
    info = PngImagePlugin.PngInfo()
    info.add_text("Title", "SECRET_DESY3_CLUSTER_PROJECTION_MODEL")
    info.add_text("Author", "Jane Researcher")
    info.add_text("Software", "matplotlib_secret_script_fig9_CPF2_NEGATIVE.py")
    info.add_text("Description", "Project Esteves2026 Section 3.2 secret truth")
    img.save(path, format="PNG", pnginfo=info)


def test_png_metadata_and_secret_strings_are_completely_stripped(tmp_path: Path) -> None:
    leaky = tmp_path / "fig9_secret_DESY3_CPF2_NEGATIVE.png"
    _make_leaky_png(leaky)

    raw_bytes = leaky.read_bytes()
    assert b"SECRET_DESY3_CLUSTER_PROJECTION_MODEL" in raw_bytes
    assert b"matplotlib_secret_script" in raw_bytes

    prepared = prepare_blind_image(leaky)
    assert prepared.source_format == "PNG"
    assert prepared.width_px == 800
    assert prepared.height_px == 600
    assert "Title" in prepared.stripped_metadata_keys
    assert "Software" in prepared.stripped_metadata_keys

    # Verify zero secret bytes survive in the re-encoded PNG
    assert b"SECRET_DESY3" not in prepared.png_bytes
    assert b"matplotlib_secret_script" not in prepared.png_bytes
    assert b"Esteves2026" not in prepared.png_bytes
    assert b"CPF2" not in prepared.png_bytes

    # Verify PIL sees zero text chunks on re-open
    with Image.open(io.BytesIO(prepared.png_bytes)) as clean_img:
        assert clean_img.mode == "RGB"
        assert clean_img.info == {}


def test_pdf_figure_renders_to_clean_metadata_stripped_png(tmp_path: Path) -> None:
    pdf_path = tmp_path / "secret_paper_fig7_B1_NOHOST.pdf"
    doc = pymupdf.open()
    doc.set_metadata(
        {
            "title": "SECRET_PDF_TITLE_ESTEVES2026",
            "author": "Secret Author",
            "creator": "matplotlib_secret.py",
        }
    )
    page = doc.new_page(width=400, height=300)
    page.insert_text((50, 150), "X vs Y Test Plot", fontsize=18)
    doc.save(str(pdf_path))
    doc.close()

    prepared = prepare_blind_image(pdf_path, page=1, dpi=150)
    assert prepared.source_format == "PDF"
    assert prepared.source_page == 1
    assert prepared.width_px > 600
    assert "title" in prepared.stripped_metadata_keys
    assert b"SECRET_PDF_TITLE" not in prepared.png_bytes
    assert b"matplotlib_secret" not in prepared.png_bytes


def test_isolated_sandbox_anonymizes_filename_and_cleans_up(tmp_path: Path) -> None:
    leaky = tmp_path / "super_leaky_filename_DESY3_B1_CPF2.png"
    _make_leaky_png(leaky)
    prepared = prepare_blind_image(leaky)

    with IsolatedBlindSandbox(prepared) as sandbox:
        assert sandbox.root is not None
        assert sandbox.figure_path is not None
        assert sandbox.figure_path.name == BLIND_FILENAME
        assert sandbox.figure_path.exists()
        # Only figure.png exists inside the sandbox
        entries = list(sandbox.root.iterdir())
        assert [e.name for e in entries] == [BLIND_FILENAME]
        # Sandbox is completely outside the original directory
        assert tmp_path not in sandbox.root.parents
        root_dir = sandbox.root

    # Deterministically deleted on exit
    assert not root_dir.exists()


def test_inspect_figure_pixels_reports_metadata_and_resolution_warnings(tmp_path: Path) -> None:
    small = tmp_path / "tiny_plot.png"
    img = Image.new("RGB", (300, 200), (255, 255, 255))
    info = PngImagePlugin.PngInfo()
    info.add_text("Comment", "Generated by secret_pipeline.py")
    img.save(small, format="PNG", pnginfo=info)

    audit = inspect_figure_pixels(small)
    assert audit.width_px == 300
    assert audit.height_px == 200
    assert audit.low_resolution_warning is True
    assert "Comment" in audit.embedded_metadata_keys
    assert audit.near_white_pixel_fraction > 0.95
    assert any("Low resolution" in w for w in audit.warnings)
    assert "95% (default)" in audit.diverging_percentile_guide
